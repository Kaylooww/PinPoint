"""Rebuild the demo workspaces and wait until every file is ready.

Run with the MinerU server and the backend already running:
  cd backend && .venv/bin/python scripts/reset_demo.py [--api http://localhost:8000]

For each demo workspace it deletes only backend/data/<id>/ (files, blocks, notes, history,
crops, connected folders), recreates the workspace through the API, uploads every
supported file from its demo folder, and polls until each file is ready. Exits 1 if any
file fails or times out.

  Reyes & Partners (Law office): backend/demo_files/reyes-partners/, else files directly
    in backend/demo_files/, else backend/samples/ (real documents; git-ignored)
  Villanueva Accounting (Accounting): backend/demo_files/villanueva-accounting/
    (fictional; generated by scripts/make_demo_files.py, run automatically if missing)
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import time
from pathlib import Path

import httpx

BACKEND = Path(__file__).resolve().parent.parent
DATA_DIR = BACKEND / "data"
DEMO = BACKEND / "demo_files"
SUPPORTED = {"pdf", "png", "jpg", "jpeg", "webp", "docx", "xlsx", "pptx", "csv", "md", "txt"}
WORKSPACES = [
    ("reyes-partners", "Reyes & Partners", "Law office", [DEMO / "reyes-partners", DEMO, BACKEND / "samples"]),
    ("villanueva-accounting", "Villanueva Accounting", "Accounting", [DEMO / "villanueva-accounting"]),
]


def supported_files(folder: Path) -> list[Path]:
    return sorted(
        p for p in folder.glob("*") if p.is_file() and not p.name.startswith(".") and p.suffix.lower().lstrip(".") in SUPPORTED
    )


def demo_files(ws_id: str, folders: list[Path]) -> tuple[Path, list[Path]] | None:
    if ws_id == "villanueva-accounting" and not supported_files(folders[0]):
        print("Generating the fictional Villanueva Accounting documents…")
        subprocess.run([sys.executable, str(BACKEND / "scripts" / "make_demo_files.py")], check=True)
    for folder in folders:
        files = supported_files(folder)
        if files:
            return folder, files
    return None


def rebuild(client: httpx.Client, ws_id: str, name: str, industry: str, folders: list[Path], timeout: int) -> bool:
    found = demo_files(ws_id, folders)
    if found is None:
        print(f"{name}: no demo files in {', '.join(str(f.relative_to(BACKEND)) for f in folders)}; skipped.")
        return False
    folder, files = found
    print(f"\n{name}: {len(files)} files from backend/{folder.relative_to(BACKEND)}/")
    if folder == BACKEND / "samples":
        print("  (backend/demo_files/reyes-partners/ is missing or empty: using backend/samples/ instead.)")

    target = DATA_DIR / ws_id
    if target.exists():
        shutil.rmtree(target)
    created = client.post("/api/workspaces", json={"name": name, "industry": industry})
    created.raise_for_status()
    got = created.json()["id"]
    if got != ws_id:
        # The backend re-seeded an empty workspace in between (e.g. a --reload restart).
        # Use that one and drop the duplicate we just made.
        if (target / "workspace.json").exists() and got.startswith(f"{ws_id}-"):
            shutil.rmtree(DATA_DIR / got)
        else:
            print(f"  Unexpected workspace id {got!r}; is a stale folder in backend/data?")
            return False
    client.post(f"/api/workspaces/{ws_id}/files", files=[("files", (p.name, p.read_bytes())) for p in files]).raise_for_status()

    started, last = time.monotonic(), ""
    while True:
        items = client.get(f"/api/workspaces/{ws_id}/files").json()
        summary = ", ".join(f"{f['name']}: {f['status']}" for f in items)
        if summary != last:
            print(f"  [{round(time.monotonic() - started):>3}s] {summary}")
            last = summary
        if all(f["status"] in ("ready", "failed") for f in items):
            break
        if time.monotonic() - started > timeout:
            print(f"  Timed out after {timeout}s.")
            return False
        time.sleep(2)
    failed = [f for f in items if f["status"] == "failed"]
    for f in failed:
        print(f"  FAILED  {f['name']}: {f.get('error')}")
    pages = sum(f["pages"] for f in items if f["status"] == "ready")
    print(f"  {'Done' if not failed else 'Finished with failures'}: {len(items) - len(failed)}/{len(items)} files ready, {pages} pages.")
    return not failed


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--api", default="http://localhost:8000", help="backend base URL")
    parser.add_argument("--timeout", type=int, default=900, help="seconds to wait for parsing, per workspace")
    args = parser.parse_args()
    api = args.api.rstrip("/")

    with httpx.Client(base_url=api, timeout=120) as client:
        try:
            health = client.get("/api/health").json()
        except httpx.HTTPError:
            print(f"The backend isn't reachable at {api}. Start it first (see docs/DEMO.md).")
            return 1
        parse_ok = health.get("mineru", {}).get("status", {}).get("parse_server", {}).get("local", {}).get("healthy")
        print(f"Health: llm ok={health['llm'].get('ok')} ({health['llm'].get('provider')}), MinerU parse server healthy={parse_ok}")
        if not parse_ok:
            print("MinerU's parse server isn't healthy. Run: mineru server start, then check mineru server status --json")
            return 1
        results = [rebuild(client, ws_id, name, industry, folders, args.timeout) for ws_id, name, industry, folders in WORKSPACES]

    print("\nAll demo workspaces ready." if all(results) else "\nSome demo workspaces need attention (see above).")
    return 0 if all(results) else 1


if __name__ == "__main__":
    sys.exit(main())
